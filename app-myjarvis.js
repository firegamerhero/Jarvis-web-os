registerApp("myjarvis", () => {
    return {
        title: "My JARVIS Core",
        icon: "fa-microchip",
        width: 600,
        height: 550,
        content: `
            <div style="display: flex; flex-direction: column; gap: 20px; padding: 10px;">
                
                <div style="text-align: center; border-bottom: 1px solid var(--glass-border); padding-bottom: 15px;">
                    <i class="fa-solid fa-server" style="font-size: 3rem; color: var(--primary-color); margin-bottom: 10px; filter: drop-shadow(0 0 10px var(--primary-color));"></i>
                    <h2 style="color: var(--text-main); font-weight: normal; letter-spacing: 2px;">SYSTEM CONFIGURATION</h2>
                </div>

                <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 20px;">
                    
                    <!-- Theme Selector -->
                    <div style="background: rgba(0,0,0,0.4); padding: 15px; border-radius: 8px; border: 1px solid var(--primary-dim);">
                        <h4 style="color: var(--primary-color); margin-bottom: 10px;"><i class="fa-solid fa-palette"></i> Hologram Color</h4>
                        <div style="display: flex; gap: 10px;">
                            <button class="sys-btn theme-btn" data-theme="theme-blue" style="background: #00f0ff; color: #000; flex: 1;">Blue</button>
                            <button class="sys-btn theme-btn" data-theme="theme-red" style="background: #ff2a2a; color: #fff; flex: 1;">Red</button>
                            <button class="sys-btn theme-btn" data-theme="theme-green" style="background: #00ff88; color: #000; flex: 1;">Green</button>
                        </div>
                    </div>

                    <!-- NEW DYNAMIC MEDIA WALLPAPERS -->
                    <div style="background: rgba(0,0,0,0.4); padding: 15px; border-radius: 8px; border: 1px solid var(--primary-dim);">
                        <h4 style="color: var(--primary-color); margin-bottom: 10px;"><i class="fa-solid fa-image"></i> Custom Wallpapers</h4>
                        <div id="wallpaper-list" style="display: flex; gap: 10px; flex-wrap: wrap;">
                            <!-- Buttons auto-generated by JS below -->
                        </div>
                        <div style="margin-top: 10px; font-size: 0.75rem; color: var(--text-muted);">
                            <button id="btn-reset-bg" class="sys-btn" style="width: 100%;">Reset Default Space BG</button>
                        </div>
                    </div>

                    <!-- Refresh Rate Booster -->
                    <div style="background: rgba(0,0,0,0.4); padding: 15px; border-radius: 8px; border: 1px solid var(--primary-dim); grid-column: span 2;">
                        <h4 style="color: var(--primary-color); margin-bottom: 10px;"><i class="fa-solid fa-bolt"></i> Display Overclock</h4>
                        <div style="display: flex; align-items: center; gap: 15px;">
                            <select id="refresh-rate" style="flex: 1; padding: 10px; background: rgba(0,0,0,0.8); color: var(--primary-color); border: 1px solid var(--primary-color); border-radius: 5px; outline: none; font-size: 1.1rem; cursor: pointer;">
                                <option value="60">60 Hz (Standard)</option>
                                <option value="120">120 Hz (Smooth)</option>
                                <option value="144">144 Hz (Gaming)</option>
                                <option value="180">180 Hz (Ultra)</option>
                                <option value="244">244 Hz (Extreme)</option>
                                <option value="510">510 Hz (Experimental)</option>
                                <option value="644">644 Hz (Quantum Max)</option>
                            </select>
                            <span id="hz-status" style="color: var(--text-muted); font-family: monospace; width: 150px; text-align: right;">Locked at 60 Hz</span>
                        </div>
                    </div>

                    <!-- DANGEROUS PERFORMANCE BOOSTER -->
                    <div style="background: rgba(255,0,60,0.1); padding: 15px; border-radius: 8px; border: 1px solid var(--danger); grid-column: span 2; text-align: center;">
                        <h4 style="color: var(--danger); margin-bottom: 10px;"><i class="fa-solid fa-triangle-exclamation"></i> PROTOCOL OVERDRIVE</h4>
                        <p style="font-size: 0.85rem; color: var(--text-muted); margin-bottom: 15px;">Warning: Disabling safety limiters may cause system instability.</p>
                        <button id="btn-dangerous" style="width: 100%; padding: 15px; background: transparent; border: 2px solid var(--danger); color: var(--danger); font-size: 1.2rem; font-weight: bold; border-radius: 5px; cursor: pointer; transition: 0.3s; text-shadow: 0 0 10px var(--danger); box-shadow: inset 0 0 15px rgba(255,0,60,0.2);">
                            ACTIVATE DANGEROUS MODE
                        </button>
                    </div>

                </div>
            </div>
            
            <style>
                .sys-btn {
                    padding: 8px;
                    border: 1px solid var(--primary-dim);
                    background: transparent;
                    color: var(--text-main);
                    border-radius: 5px;
                    cursor: pointer;
                    transition: 0.2s;
                    font-weight: bold;
                }
                .sys-btn:hover {
                    box-shadow: var(--glow-shadow);
                    border-color: var(--primary-color);
                }
                #btn-dangerous:hover {
                    background: var(--danger);
                    color: #fff;
                    box-shadow: 0 0 20px var(--danger);
                }
            </style>
        `,
        onInit: (win) => {
            // ==========================================
            // DYNAMIC WALLPAPER LIST
            // You can add as many .png or .mp4 files here as you want!
            // ==========================================
            const myWallpapers = [
                { id: "1", filename: "bg1.png" },
                { id: "2", filename: "bg2.png" },
                { id: "3", filename: "video1.mp4" },
                { id: "4", filename: "video2.mp4" }
            ];

            const wallpaperList = win.querySelector("#wallpaper-list");
            const videoBgLayer = document.getElementById("video-bg");

            // Auto-generate wallpaper buttons
            myWallpapers.forEach(wp => {
                const btn = document.createElement("button");
                btn.className = "sys-btn";
                btn.textContent = wp.id;
                btn.style.flex = "1";
                btn.style.minWidth = "40px";
                
        // Inside myWallpapers.forEach loop in app-myjarvis.js:
btn.addEventListener("click", () => {
    const file = wp.filename;
    const isVideo = file.endsWith(".mp4") || file.endsWith(".webm");

    if (isVideo) {
        document.body.style.backgroundImage = "none";
        videoBgLayer.src = file;
        videoBgLayer.style.display = "block";
        videoBgLayer.play().catch(err => console.warn("Video autoplay pending user interaction:", err));
    } else {
        videoBgLayer.style.display = "none";
        videoBgLayer.pause();
        videoBgLayer.removeAttribute("src");
        videoBgLayer.load();
        
        document.body.style.backgroundImage = `url('${file}')`;
        document.body.style.backgroundSize = "cover";
        document.body.style.backgroundPosition = "center";
        document.body.style.backgroundRepeat = "no-repeat";
    }
});

                
                wallpaperList.appendChild(btn);
            });

            // Reset back to CSS defaults
            win.querySelector("#btn-reset-bg").addEventListener("click", () => {
                videoBgLayer.style.display = "none";
                videoBgLayer.pause();
                videoBgLayer.src = "";
                document.body.style.backgroundImage = "";
                document.body.className = "bg-1 theme-blue"; // Reset to defaults
            });

            // Theme Switching Logic
            const themeBtns = win.querySelectorAll(".theme-btn");
            themeBtns.forEach(btn => {
                btn.addEventListener("click", (e) => {
                    const newTheme = e.target.getAttribute("data-theme");
                    document.body.classList.remove("theme-blue", "theme-red", "theme-green");
                    document.body.classList.add(newTheme);
                });
            });

            // Fake Refresh Rate Logic
            const hzSelect = win.querySelector("#refresh-rate");
            const hzStatus = win.querySelector("#hz-status");
            hzSelect.addEventListener("change", (e) => {
                const val = e.target.value;
                hzStatus.style.color = "var(--primary-color)";
                hzStatus.textContent = "Calibrating...";
                
                setTimeout(() => {
                    hzStatus.textContent = `Boosted to ${val} Hz`;
                    hzStatus.style.color = "#00ff88"; 
                }, 800);
            });

            // Dangerous Mode Logic
            const dangerBtn = win.querySelector("#btn-dangerous");
            let isDangerous = false;

            dangerBtn.addEventListener("click", () => {
                isDangerous = !isDangerous;
                
                if (isDangerous) {
                    document.body.classList.add("dangerous-mode");
                    dangerBtn.textContent = "DEACTIVATE PROTOCOL";
                    dangerBtn.style.background = "var(--danger)";
                    dangerBtn.style.color = "#fff";
                    
                    const banner = document.createElement("div");
                    banner.className = "overdrive-banner";
                    banner.id = "active-overdrive-banner";
                    banner.textContent = "SYSTEM OVERDRIVE ENGAGED: DANGER";
                    document.body.appendChild(banner);
                } else {
                    document.body.classList.remove("dangerous-mode");
                    dangerBtn.textContent = "ACTIVATE DANGEROUS MODE";
                    dangerBtn.style.background = "transparent";
                    dangerBtn.style.color = "var(--danger)";
                    
                    const banner = document.getElementById("active-overdrive-banner");
                    if (banner) banner.remove();
                }
            });
        }
    };
});
